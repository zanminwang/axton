use serde_json::Value;
use std::fmt::Write;
fn arr<'a>(v: &'a Value, k: &str) -> &'a Vec<Value> {
    v[k].as_array().unwrap()
}
fn s<'a>(v: &'a Value, k: &str) -> &'a str {
    v[k].as_str().unwrap()
}
/// Deprecation notices are generated-code hints only ([#91](https://github.com/zanminwang/axton/issues/91)):
/// `Some(reason)` when the field, enum value or slot carries `@deprecated`.
fn deprecation<'a>(v: &'a Value, kind: &str, keys: &[(&str, &str)]) -> Option<&'a Value> {
    v["deprecations"]
        .as_array()?
        .iter()
        .find(|d| d["kind"] == kind && keys.iter().all(|(k, x)| d[*k] == *x))
        .map(|d| &d["reason"])
}
/// A JSDoc line for a deprecated member, or nothing.
fn ts_deprecated(reason: Option<&Value>) -> String {
    match reason {
        None => String::new(),
        Some(Value::String(r)) => format!(" /** @deprecated {r} */\n"),
        Some(_) => " /** @deprecated */\n".into(),
    }
}
/// A Dart `@Deprecated` annotation for a deprecated member, or nothing.
fn dart_deprecated(reason: Option<&Value>, trailing: &str) -> String {
    match reason {
        None => String::new(),
        Some(r) => format!(
            "@Deprecated('{}'){trailing}",
            r.as_str()
                .unwrap_or("")
                .replace('\\', "\\\\")
                .replace('\'', "\\'")
        ),
    }
}
fn lower(s: &str) -> String {
    let mut c = s.chars();
    format!("{}{}", c.next().unwrap().to_lowercase(), c.as_str())
}
fn ty(t: &Value, dart: bool) -> String {
    if t["kind"] == "list" {
        let e = ty(&t["element"], dart);
        return if dart {
            format!("List<{e}>")
        } else {
            format!("{e}[]")
        };
    }
    if t["kind"] == "enum" {
        return s(t, "name").into();
    }
    match s(t, "name") {
        "boolean" => {
            if dart {
                "bool"
            } else {
                "boolean"
            }
        }
        "int" => {
            if dart {
                "int"
            } else {
                "number"
            }
        }
        "float" => {
            if dart {
                "double"
            } else {
                "number"
            }
        }
        "dateTime" => {
            if dart {
                "DateTime"
            } else {
                "Date"
            }
        }
        _ => {
            if dart {
                "String"
            } else {
                "string"
            }
        }
    }
    .into()
}
/// Whether a fresh create may omit this field: it carries a creation default.
fn defaulted(f: &Value) -> bool {
    f.get("createDefault").is_some_and(|d| !d.is_null())
}
fn ft(f: &Value, dart: bool) -> String {
    format!(
        "{}{}",
        ty(&f["type"], dart),
        if f["nullable"] == true {
            if dart { "?" } else { " | null" }
        } else {
            ""
        }
    )
}
fn decode(t: &Value, x: &str, dart: bool) -> String {
    if t["kind"] == "list" {
        let e = decode(&t["element"], "e", dart);
        return if dart {
            format!("({x} as List).map((e) => {e}).toList()")
        } else {
            format!("({x} as unknown[]).map(e => {e})")
        };
    }
    if t["kind"] == "enum" {
        let n = s(t, "name");
        return if dart {
            format!("{n}.values.byName({x} as String)")
        } else {
            format!("{x} as {n}")
        };
    }
    if t["name"] == "dateTime" {
        return if dart {
            format!("DateTime.parse({x} as String)")
        } else {
            format!("new Date({x} as string)")
        };
    }
    if dart && t["name"] == "float" {
        format!("({x} as num).toDouble()")
    } else {
        format!("{x} as {}", ty(t, dart))
    }
}
fn encoded(t: &Value, x: &str, dart: bool) -> String {
    if t["kind"] == "list" {
        let e = encoded(&t["element"], "e", dart);
        return if dart {
            format!("{x}.map((e) => {e}).toList()")
        } else {
            format!("{x}.map(e => {e})")
        };
    }
    if t["name"] == "dateTime" {
        return if dart {
            format!("{x}.toUtc().toIso8601String()")
        } else {
            format!("{x}.toISOString()")
        };
    }
    if dart && t["kind"] == "enum" {
        format!("{x}.name")
    } else {
        x.into()
    }
}
fn enc(f: &Value, x: &str, dart: bool) -> String {
    let e = encoded(
        &f["type"],
        &if dart && f["nullable"] == true {
            format!("{x}!")
        } else {
            x.into()
        },
        dart,
    );
    if f["nullable"] == true {
        format!("{x} == null ? null : {e}")
    } else {
        e
    }
}
pub fn typescript(v: &Value) -> String {
    let mut o = String::from(
        "// Generated by axton. Do not edit.\nimport type { Call, CallOptions } from './client.ts';\nexport interface ReadPort { read(model:string,identity:object):Promise<Record<string,unknown>|null>; querySpec(model:string,query:object):Promise<Record<string,unknown>[]>; related(model:string,identity:object,relation:string):Promise<Record<string,unknown>|null>; referencing(model:string,identity:object,source:string,relation:string):Promise<Record<string,unknown>[]>; }\nexport interface WritePort extends ReadPort { direct(operation:object):Promise<void>; }\nexport interface LivePort extends WritePort { watch(model:string,where:Record<string,unknown>,listener:(rows:Record<string,unknown>[])=>void,onError?:(error:unknown)=>void):()=>void; syncState(model:string,identity:object):Promise<unknown>; }\nexport interface CallPort { invokeAction<T>(name:string,version:number,args:object,decode:(value:unknown)=>T,options?:CallOptions):Promise<Call<T>>; invokeDirectAction<T>(name:string,version:number,args:object,decode:(value:unknown)=>T,options?:CallOptions):Promise<T>; }\n",
    );
    if !arr(v, "mutations").is_empty() {
        o.push_str("export interface MutatePort { mutate(value:object):Promise<number>; }\n");
    }
    writeln!(o, "export const schema = {} as const;", v["schema"]).unwrap();
    ts_sync_state(v, &mut o);
    for en in arr(&v["schema"], "enums") {
        for value in arr(en, "values") {
            if let Some(reason) = deprecation(
                v,
                "enumValue",
                &[("enum", s(en, "name")), ("value", value.as_str().unwrap())],
            ) {
                match reason {
                    Value::String(r) => writeln!(o, "/** @deprecated {value}: {r} */").unwrap(),
                    _ => writeln!(o, "/** @deprecated {value} */").unwrap(),
                }
            }
        }
        writeln!(
            o,
            "export type {} = {};",
            s(en, "name"),
            arr(en, "values")
                .iter()
                .map(|x| x.to_string())
                .collect::<Vec<_>>()
                .join(" | ")
        )
        .unwrap();
    }
    for m in arr(&v["schema"], "models") {
        let n = s(m, "name");
        for (suffix, filter, partial) in
            [("", 0, false), ("Identity", 1, false), ("Patch", 2, true)]
        {
            writeln!(o, "export interface {n}{suffix} {{").unwrap();
            for f in arr(m, "fields") {
                let id = arr(m, "identity").contains(&f["name"]);
                if (filter == 1 && !id) || (filter == 2 && id) {
                    continue;
                }
                o.push_str(&ts_deprecated(deprecation(
                    v,
                    "field",
                    &[("model", n), ("field", s(f, "name"))],
                )));
                writeln!(
                    o,
                    " {}{}: {};",
                    s(f, "name"),
                    if partial { "?" } else { "" },
                    ft(f, false)
                )
                .unwrap();
            }
            o.push_str("}\n");
        }
        // What a fresh create accepts: a field with a creation default may be
        // omitted (the client fills it once before persisting or sending).
        writeln!(o, "export interface {n}Create {{").unwrap();
        for f in arr(m, "fields") {
            o.push_str(&ts_deprecated(deprecation(
                v,
                "field",
                &[("model", n), ("field", s(f, "name"))],
            )));
            writeln!(
                o,
                " {}{}: {};",
                s(f, "name"),
                if defaulted(f) { "?" } else { "" },
                ft(f, false)
            )
            .unwrap();
        }
        o.push_str("}\n");
        writeln!(
            o,
            "export function decode{n}(row:Record<string,unknown>):{n} {{ return {{"
        )
        .unwrap();
        for f in arr(m, "fields") {
            let k = s(f, "name");
            let x = format!("row.{k}");
            let dec = decode(&f["type"], &x, false);
            writeln!(
                o,
                " {k}: {},",
                if f["nullable"] == true {
                    format!("{x} == null ? null : {dec}")
                } else {
                    dec
                }
            )
            .unwrap();
        }
        o.push_str("}; }\n");
        writeln!(
            o,
            "export function decode{n}Identity(row:Record<string,unknown>):{n}Identity {{ return {{"
        )
        .unwrap();
        for f in arr(m, "fields") {
            if !arr(m, "identity").contains(&f["name"]) {
                continue;
            }
            let k = s(f, "name");
            let x = format!("row.{k}");
            writeln!(o, " {k}: {},", decode(&f["type"], &x, false)).unwrap();
        }
        o.push_str("}; }\n");
        for (suffix, partial) in [
            ("", false),
            ("Identity", false),
            ("Patch", true),
            ("Where", true),
        ] {
            let input = if suffix == "Where" {
                format!("Partial<{n}>")
            } else {
                format!("{n}{suffix}")
            };
            writeln!(o,"export function encode{n}{suffix}(value:{input}):Record<string,unknown> {{ return {{").unwrap();
            for f in arr(m, "fields") {
                let id = arr(m, "identity").contains(&f["name"]);
                if (suffix == "Identity" && !id) || (suffix == "Patch" && id) {
                    continue;
                }
                let k = s(f, "name");
                let ex = enc(f, &format!("value.{k}"), false);
                if partial {
                    writeln!(o, " ...(value.{k} !== undefined ? {{ {k}: {ex} }} : {{}}),").unwrap()
                } else {
                    writeln!(o, " {k}: {ex},").unwrap()
                }
            }
            o.push_str("}; }\n");
        }
    }
    for m in arr(&v["schema"], "models") {
        let n = s(m, "name");
        for (suffix, identity_only) in [("", false), ("Identity", true)] {
            writeln!(o, "export function encode{n}Create{suffix}(value:{n}Create):Record<string,unknown> {{ return {{").unwrap();
            for f in arr(m, "fields") {
                if identity_only && !arr(m, "identity").contains(&f["name"]) {
                    continue;
                }
                let k = s(f, "name");
                let ex = enc(f, &format!("value.{k}"), false);
                if defaulted(f) {
                    writeln!(o, " ...(value.{k} !== undefined ? {{ {k}: {ex} }} : {{}}),").unwrap()
                } else {
                    writeln!(o, " {k}: {ex},").unwrap()
                }
            }
            o.push_str("}; }\n");
        }
    }
    for mu in arr(v, "mutations") {
        let n = s(mu, "name");
        writeln!(o, "export interface {n}Args {{").unwrap();
        for slot in arr(mu, "slots") {
            let model = s(slot, "model");
            let input = match s(slot, "operation") {
                "create" => format!("{model}Create"),
                "delete" => format!("{model}Identity"),
                _ => {
                    let patch = if let Some(a) = slot["allowedPatchFields"].as_array() {
                        format!(
                            "Pick<{model}Patch, {}>",
                            if a.is_empty() {
                                "never".into()
                            } else {
                                a.iter()
                                    .map(Value::to_string)
                                    .collect::<Vec<_>>()
                                    .join(" | ")
                            }
                        )
                    } else {
                        format!("{model}Patch")
                    };
                    format!("{{ identity:{model}Identity; values:{patch} }}")
                }
            };
            let card = s(slot, "cardinality");
            o.push_str(&ts_deprecated(deprecation(
                v,
                "slot",
                &[("mutation", n), ("slot", s(slot, "name"))],
            )));
            writeln!(
                o,
                " {}{}: {}{};",
                s(slot, "name"),
                if card == "optional" { "?" } else { "" },
                input,
                if card == "list" { "[]" } else { "" }
            )
            .unwrap();
        }
        o.push_str("}\n");
        writeln!(
            o,
            "export function {n}(args:{n}Args) {{ const operations:object[] = [];"
        )
        .unwrap();
        for slot in arr(mu, "slots") {
            let model = s(slot, "model");
            let key = s(slot, "name");
            let op = s(slot, "operation");
            let card = s(slot, "cardinality");
            writeln!(
                o,
                " for (const value of {}) {{",
                if card == "list" {
                    format!("args.{key}")
                } else if card == "optional" {
                    format!("args.{key} === undefined ? [] : [args.{key}]")
                } else {
                    format!("[args.{key}]")
                }
            )
            .unwrap();
            let id = if op == "update" {
                "value.identity"
            } else {
                "value"
            };
            let vals = if op == "delete" {
                String::new()
            } else if op == "update" {
                format!(", values:encode{model}Patch(value.values)")
            } else {
                format!(", values:encode{model}Patch(value)")
            };
            let identity = if op == "create" {
                "CreateIdentity"
            } else {
                "Identity"
            };
            writeln!(o," operations.push({{ model:'{model}', op:'{op}', identity:encode{model}{identity}({id}){vals} }}); }}").unwrap();
        }
        writeln!(
            o,
            " return {{name:'{n}',version:{},operations}}; }}",
            mu["version"]
        )
        .unwrap();
    }
    ts_models(v, &mut o);
    ts_actions(v, &mut o);
    if !arr(v, "mutations").is_empty() {
        o.push_str("export class Mutate { readonly port:MutatePort; constructor(port:MutatePort) { this.port=port; }\n");
        for mu in arr(v, "mutations") {
            let n = s(mu, "name");
            writeln!(
                o,
                " {}(args:{n}Args):Promise<number> {{ return this.port.mutate({n}(args)); }}",
                lower(n)
            )
            .unwrap();
        }
        o.push_str("}\n");
    }
    let names: Vec<(String, &str)> = arr(&v["schema"], "models")
        .iter()
        .map(|m| (lower(s(m, "name")), s(m, "name")))
        .collect();
    for (suffix, port) in [("Live", "LivePort"), ("Tx", "WritePort")] {
        writeln!(
            o,
            "export interface {suffix}Models {{ {} }}",
            names
                .iter()
                .map(|(key, n)| format!("{key}:{n}{suffix}Model;"))
                .collect::<Vec<_>>()
                .join(" ")
        )
        .unwrap();
        writeln!(
            o,
            "export function {}Models(port:{port}):{suffix}Models {{ return {{ {} }}; }}",
            lower(suffix),
            names
                .iter()
                .map(|(key, n)| format!("{key}:new {n}{suffix}Model(port)"))
                .collect::<Vec<_>>()
                .join(", ")
        )
        .unwrap();
    }
    o.push_str("export class GeneratedTransaction { readonly transaction:WritePort; readonly models:TxModels; constructor(transaction:WritePort) { this.transaction=transaction; this.models=txModels(transaction); } }\n");
    o
}
/// The typed shape of a record's sync state. Mutation names are the schema's,
/// so a pending entry's `name` is checked against them.
fn ts_sync_state(v: &Value, o: &mut String) {
    let mut names: Vec<String> = arr(v, "mutations")
        .iter()
        .map(|m| format!("'{}'", s(m, "name")))
        .collect();
    names.sort();
    names.dedup();
    let union = if names.is_empty() {
        "string".to_string()
    } else {
        names.join("|")
    };
    writeln!(o, "export type MutationName = {union};").unwrap();
    o.push_str("export interface PendingMutation { ordinal:number; name:MutationName; phase:'queued'|'frozen'; prerequisites:{key:string;state:'ready'|'pending'|'failed'}[]; diverged?:boolean; }\n");
    o.push_str(
        "export interface Rejection { ordinal:number; code:string; [key:string]:unknown; }\n",
    );
    o.push_str(
        "export interface SyncState { pending:PendingMutation[]; rejections:Rejection[]; }\n",
    );
}
fn slot_input_type(slot: &Value) -> String {
    let model = s(slot, "model");
    let one = match s(slot, "operation") {
        "create" => model.to_string(),
        "delete" => format!("{{ identity: {model}Identity }}"),
        _ => {
            let patch = match slot["allowedPatchFields"].as_array() {
                Some(a) if a.is_empty() => format!("Pick<{model}Patch, never>"),
                Some(a) => format!(
                    "Pick<{model}Patch, {}>",
                    a.iter()
                        .map(Value::to_string)
                        .collect::<Vec<_>>()
                        .join(" | ")
                ),
                None => format!("{model}Patch"),
            };
            format!("{{ identity: {model}Identity; patch: {patch} }}")
        }
    };
    match s(slot, "cardinality") {
        "list" => format!("{one}[]"),
        "optional" => format!("{one} | null"),
        _ => one,
    }
}
fn action_cardinality(base: &str, cardinality: &str) -> String {
    match cardinality {
        "optional" => format!("{base} | null"),
        "list" => format!("{base}[]"),
        _ => base.to_string(),
    }
}
/// A current operation input's TypeScript type. Client create operands may
/// omit defaulted fields; `handler` types are the complete values handlers receive.
fn action_input_type(input: &Value, handler: bool) -> String {
    if input["kind"] == "value" {
        let mut base = ty(&input["type"], false);
        if input["list"] == true {
            base.push_str("[]");
        }
        return if input["nullable"] == true {
            format!("{base} | null")
        } else {
            base
        };
    }
    let model = s(input, "model");
    let base = match s(input, "operation") {
        "create" if handler => model.to_string(),
        "create" => format!("{model}Create"),
        "delete" => format!("{model}Delete"),
        _ => {
            let keys = input["allowedPatchFields"]
                .as_array()
                .map(|fields| {
                    if fields.is_empty() {
                        "never".to_string()
                    } else {
                        fields
                            .iter()
                            .map(Value::to_string)
                            .collect::<Vec<_>>()
                            .join(" | ")
                    }
                })
                .unwrap_or_else(|| format!("keyof {model}Patch"));
            format!("{model}Update<{keys}>")
        }
    };
    action_cardinality(&base, s(input, "cardinality"))
}
fn action_output_type(output: &Value, handler: bool) -> String {
    let base = match s(output, "kind") {
        "value" => ty(&output["type"], false),
        "deleteIdentity" => format!("{}Identity", s(output, "model")),
        "model" if handler => format!("{}Identity", s(output, "model")),
        "model" => s(output, "model").to_string(),
        _ => unreachable!(),
    };
    action_cardinality(&base, s(output, "cardinality"))
}
fn action_type_name(action: &Value, latest: u64, suffix: &str) -> String {
    let name = s(action, "name");
    let version = action["version"].as_u64().unwrap();
    if version == latest {
        format!("{name}{suffix}")
    } else {
        format!("{name}V{version}{suffix}")
    }
}
fn snapshot_type(ty_value: &Value, enums: &Value) -> String {
    if ty_value["kind"] == "list" {
        return format!("{}[]", snapshot_type(&ty_value["element"], enums));
    }
    if ty_value["kind"] == "enum"
        && let Some(en) = enums
            .as_array()
            .and_then(|list| list.iter().find(|en| en["name"] == ty_value["name"]))
    {
        return arr(en, "values")
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | ");
    }
    ty(ty_value, false)
}
fn snapshot_field_type(field: &Value, enums: &Value) -> String {
    let base = snapshot_type(&field["type"], enums);
    if field["nullable"] == true {
        format!("{base} | null")
    } else {
        base
    }
}
fn historical_action_input_type(arg: &Value, action: &Value, latest: u64) -> String {
    if action["version"].as_u64() == Some(latest) {
        return action_input_type(arg, true);
    }
    if arg["kind"] == "value" {
        let mut base = snapshot_type(&arg["type"], &action["input"]["enums"]);
        if arg["list"] == true {
            base = format!("({base})[]");
        }
        return if arg["nullable"] == true {
            format!("{base} | null")
        } else {
            base
        };
    }
    let prefix = action_type_name(action, latest, "");
    let model = s(arg, "model");
    let base = match s(arg, "operation") {
        "create" => format!("{prefix}{model}Create"),
        "delete" => format!("{prefix}{model}Identity"),
        _ => {
            let keys = arg["allowedPatchFields"]
                .as_array()
                .map(|fields| {
                    if fields.is_empty() {
                        "never".to_string()
                    } else {
                        fields
                            .iter()
                            .map(Value::to_string)
                            .collect::<Vec<_>>()
                            .join(" | ")
                    }
                })
                .unwrap_or_else(|| format!("keyof {prefix}{model}Patch"));
            format!("{prefix}{model}Update<{keys}>")
        }
    };
    action_cardinality(&base, s(arg, "cardinality"))
}
fn backend_action_output_type(field: &Value, action: &Value, models: &[Value]) -> String {
    let base = if field["kind"] == "value" {
        snapshot_type(&field["type"], &action["outputEnums"])
    } else {
        let model = s(field, "model");
        let read_version = field["modelReadVersion"].as_u64();
        let current = models
            .iter()
            .find(|m| m["name"] == model)
            .and_then(|m| m["version"].as_u64());
        if field["kind"] == "model" && read_version != current {
            format!("{model}V{}Identity", read_version.unwrap())
        } else {
            format!("{model}Identity")
        }
    };
    if field["kind"] == "value" && field["type"]["kind"] == "enum" && field["cardinality"] == "list"
    {
        format!("({base})[]")
    } else {
        action_cardinality(&base, s(field, "cardinality"))
    }
}
fn ts_actions(v: &Value, o: &mut String) {
    let actions = arr(v, "actions");
    if actions.is_empty() {
        o.push_str("export function makeMutations(_port:CallPort) { return { call: {} }; }\nexport function makeQueries(_port:CallPort) { return { enqueue: {} }; }\n");
        return;
    }
    for model in arr(&v["schema"], "models") {
        let n = s(model, "name");
        writeln!(o, "export type {n}Update<K extends keyof {n}Patch = keyof {n}Patch> = {n}Identity & Partial<Pick<{n}Patch, K>>;").unwrap();
        writeln!(o, "export type {n}Delete = {n}Identity;").unwrap();
    }
    let mut latest = std::collections::BTreeMap::new();
    for action in actions {
        latest
            .entry(s(action, "name"))
            .and_modify(|n: &mut u64| *n = (*n).max(action["version"].as_u64().unwrap()))
            .or_insert(action["version"].as_u64().unwrap());
    }
    for action in actions {
        let n = s(action, "name");
        let version = latest[n];
        if action["version"].as_u64() != Some(version) {
            continue;
        }
        let input = action_type_name(action, version, "Input");
        let output = action_type_name(action, version, "Output");
        writeln!(o, "export interface {input} {{").unwrap();
        for arg in arr(action, "inputs") {
            let optional = arg["kind"] == "model" && arg["cardinality"] == "optional";
            writeln!(
                o,
                " {}{}: {};",
                s(arg, "name"),
                if optional { "?" } else { "" },
                action_input_type(arg, false)
            )
            .unwrap();
        }
        o.push_str("}\n");
        if arr(action, "outputs").is_empty() {
            writeln!(o, "export type {output} = void;").unwrap();
        } else {
            writeln!(o, "export interface {output} {{").unwrap();
            for field in arr(action, "outputs") {
                writeln!(
                    o,
                    " {}: {};",
                    s(field, "name"),
                    action_output_type(field, false)
                )
                .unwrap();
            }
            o.push_str("}\n");
        }
    }
    for (name, version) in &latest {
        let action = actions
            .iter()
            .find(|a| s(a, "name") == *name && a["version"].as_u64() == Some(*version))
            .unwrap();
        writeln!(
            o,
            "function encode{name}Input(args:{name}Input):Record<string,unknown> {{ return {{"
        )
        .unwrap();
        for input in arr(action, "inputs") {
            let key = s(input, "name");
            let expr = ts_action_encode_input(input, &format!("args.{key}"));
            writeln!(o, " {key}: {expr},").unwrap();
        }
        o.push_str("}; }\n");
        if arr(action, "outputs").is_empty() {
            writeln!(
                o,
                "function decode{name}Output(_value:unknown):void {{ return undefined; }}"
            )
            .unwrap();
        } else {
            writeln!(o, "function decode{name}Output(value:unknown):{name}Output {{ const row=value as Record<string,unknown>; return {{").unwrap();
            for output in arr(action, "outputs") {
                let key = s(output, "name");
                let expr = ts_action_decode_output(output, &format!("row.{key}"));
                writeln!(o, " {key}: {expr},").unwrap();
            }
            o.push_str("}; }\n");
        }
    }
    for (name, version) in &latest {
        let action = actions
            .iter()
            .find(|a| s(a, "name") == *name && a["version"].as_u64() == Some(*version))
            .unwrap();
        let keys = store_keys(action);
        writeln!(o, "/** Invocation options for {name}; `store` selects which explicit Model outputs also update local Models. */").unwrap();
        if keys.is_empty() {
            writeln!(o, "export type {name}Options = {{ store?: boolean }};").unwrap();
        } else {
            let union = keys
                .iter()
                .map(|key| format!("'{key}'"))
                .collect::<Vec<_>>()
                .join("|");
            writeln!(o, "export type {name}Options = CallOptions<{union}>;").unwrap();
        }
    }
    // Each current operation appears under its latest version's kind. The
    // method, not an option, selects delivery: the default route of each
    // kind, and the other route under `call` or `enqueue`.
    let current = |kind: axton_core::CallKind| -> Vec<(&str, u64)> {
        latest
            .iter()
            .filter(|(name, version)| {
                actions.iter().any(|a| {
                    s(a, "name") == **name
                        && a["version"].as_u64() == Some(**version)
                        && crate::action_names::kind(a) == kind
                })
            })
            .map(|(name, version)| (*name, *version))
            .collect()
    };
    let durable = |o: &mut String, indent: &str, name: &str, version: u64| {
        writeln!(o, "{indent}{}: (args:{name}Input, options?:{name}Options):Promise<Call<{name}Output>> => port.invokeAction('{name}',{version},encode{name}Input(args),decode{name}Output,options),", lower(name)).unwrap();
    };
    let direct = |o: &mut String, indent: &str, name: &str, version: u64| {
        writeln!(o, "{indent}{}: (args:{name}Input, options?:{name}Options):Promise<{name}Output> => port.invokeDirectAction('{name}',{version},encode{name}Input(args),decode{name}Output,options),", lower(name)).unwrap();
    };
    let mutations = current(axton_core::CallKind::Mutation);
    let queries = current(axton_core::CallKind::Query);
    o.push_str("/** Mutations resolve after local acceptance (durable); `call` waits for the backend outcome. */\nexport function makeMutations(port:CallPort) { return {\n");
    for (name, version) in &mutations {
        durable(o, " ", name, *version);
    }
    o.push_str(" call: {\n");
    for (name, version) in &mutations {
        direct(o, "  ", name, *version);
    }
    o.push_str(" }\n}; }\n");
    o.push_str("/** Queries resolve with the backend result (direct); `enqueue` accepts them durably. */\nexport function makeQueries(port:CallPort) { return {\n");
    for (name, version) in &queries {
        direct(o, " ", name, *version);
    }
    o.push_str(" enqueue: {\n");
    for (name, version) in &queries {
        durable(o, "  ", name, *version);
    }
    o.push_str(" }\n}; }\n");
}
/// Output names a call's `store` map may name, by the core eligibility rule.
fn store_keys(action: &Value) -> Vec<&str> {
    arr(action, "outputs")
        .iter()
        .filter(|output| crate::action_names::store_eligible(output))
        .map(|output| s(output, "name"))
        .collect()
}
/// The Dart named parameter carrying the store selector. It is `store`
/// unless a business input already uses that name.
fn dart_store_param(action: &Value) -> String {
    let taken = |name: &str| arr(action, "inputs").iter().any(|i| i["name"] == name);
    let mut name = if taken("store") {
        "outputStore".to_string()
    } else {
        "store".to_string()
    };
    while taken(&name) {
        name.push('$');
    }
    name
}
/// The typed per-Action store selector shared by both Dart entry points.
fn dart_store_class(o: &mut String, name: &str, action: &Value) {
    let keys = store_keys(action);
    writeln!(o, "/// Which explicit Model outputs of {name} also update local Models.\nfinal class {name}Store extends CallStore {{").unwrap();
    let nulls: String = keys.iter().map(|key| format!(", {key} = null")).collect();
    writeln!(o, " /// Store every eligible output (the default).\n const {name}Store.all() : _mode = 0{nulls};").unwrap();
    writeln!(o, " /// Store no output; results are returned unchanged.\n const {name}Store.none() : _mode = 1{nulls};").unwrap();
    if !keys.is_empty() {
        let params = keys
            .iter()
            .map(|key| format!("this.{key}"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(o, " /// Choose outputs by name; null leaves an output at the default (stored).\n const {name}Store.outputs({{{params}}}) : _mode = 2;").unwrap();
    }
    o.push_str(" final int _mode;\n");
    for key in &keys {
        writeln!(o, " final bool? {key};").unwrap();
    }
    let map = keys
        .iter()
        .map(|key| format!("if ({key} != null) '{key}': {key}!"))
        .collect::<Vec<_>>()
        .join(", ");
    if keys.is_empty() {
        o.push_str(" @override\n Object? toWire() => _mode == 0 ? null : false;\n}\n");
    } else {
        writeln!(o, " @override\n Object? toWire() => switch (_mode) {{ 0 => null, 1 => false, _ => <String, bool>{{{map}}} }};\n}}").unwrap();
    }
}
fn ts_action_encode_input(input: &Value, x: &str) -> String {
    if input["kind"] == "value" {
        let ty = if input["list"] == true {
            serde_json::json!({"kind":"list","element":input["type"]})
        } else {
            input["type"].clone()
        };
        let expr = encoded(&ty, x, false);
        return if input["nullable"] == true {
            format!("{x} === null ? null : {expr}")
        } else {
            expr
        };
    }
    match s(input, "cardinality") {
        "list" => format!(
            "{x}.map(value => {})",
            ts_action_encode_model_one(input, "value")
        ),
        "optional" => format!(
            "{x} == null ? null : {}",
            ts_action_encode_model_one(input, x)
        ),
        _ => ts_action_encode_model_one(input, x),
    }
}
fn ts_action_encode_model_one(input: &Value, x: &str) -> String {
    let model = s(input, "model");
    match s(input, "operation") {
        "create" => format!("encode{model}Create({x})"),
        "update" => format!("{{...encode{model}Identity({x}),...encode{model}Patch({x})}}"),
        "delete" => format!("encode{model}Identity({x})"),
        _ => unreachable!(),
    }
}
fn ts_action_decode_output(output: &Value, x: &str) -> String {
    match s(output, "cardinality") {
        "list" => format!(
            "({x} as unknown[]).map(value => {})",
            ts_action_decode_one(output, "value")
        ),
        "optional" => format!("{x} == null ? null : {}", ts_action_decode_one(output, x)),
        _ => ts_action_decode_one(output, x),
    }
}
fn ts_action_decode_one(output: &Value, x: &str) -> String {
    match s(output, "kind") {
        "value" => decode(&output["type"], x, false),
        "model" => format!(
            "decode{}({x} as Record<string,unknown>)",
            s(output, "model")
        ),
        "deleteIdentity" => format!(
            "decode{}Identity({x} as Record<string,unknown>)",
            s(output, "model")
        ),
        _ => unreachable!(),
    }
}
