/// A Dart single-quoted string literal whose value is exactly `text`: every
/// backslash, quote, dollar sign and control character is escaped, so no
/// schema content (such as a default string) can end or interpolate it.
fn dart_string(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('\'');
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '$' => out.push_str("\\$"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            c if (c as u32) < 0x20 => write!(out, "\\u{{{:x}}}", c as u32).unwrap(),
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}
/// Statement moving a create record's identity fields out of `state` into
/// `identity`. An omitted (defaulted) identity field stays omitted.
fn dart_split_identity(model: &Value) -> String {
    let keys = arr(model, "identity")
        .iter()
        .map(|k| format!("'{}'", k.as_str().unwrap()))
        .collect::<Vec<_>>()
        .join(",");
    format!(
        "final identity=<String,dynamic>{{for (final key in const <String>[{keys}]) if (state.containsKey(key)) key: state.remove(key)}};"
    )
}
/// `{Model}Create`: the omission-preserving create input. A defaulted field
/// may be left out; a defaulted nullable field uses `Present` so an explicit
/// null stays distinct from omission. Other fields are as required as in
/// the full record.
fn dart_create_class(v: &Value, m: &Value, o: &mut String) {
    let n = s(m, "name");
    let fields = arr(m, "fields");
    writeln!(o, "class {n}Create implements {n}CreateInput {{").unwrap();
    for f in fields {
        if let Some(reason) = deprecation(v, "field", &[("model", n), ("field", s(f, "name"))]) {
            o.push(' ');
            o.push_str(&dart_deprecated(Some(reason), "\n"));
        }
        let ty = match (defaulted(f), f["nullable"] == true) {
            (true, true) => format!("Present<{}>?", ft(f, true)),
            (true, false) => format!("{}?", ft(f, true)),
            (false, _) => ft(f, true),
        };
        writeln!(o, " final {ty} {};", s(f, "name")).unwrap();
    }
    writeln!(
        o,
        " const {n}Create({{{}}});",
        fields
            .iter()
            .map(|f| format!(
                "{}this.{}",
                if defaulted(f) { "" } else { "required " },
                s(f, "name")
            ))
            .collect::<Vec<_>>()
            .join(",")
    )
    .unwrap();
    o.push_str(" @override\n Map<String,dynamic> toCreateRecord() => {\n");
    for f in fields {
        let k = s(f, "name");
        let line = match (defaulted(f), f["nullable"] == true) {
            (true, true) => format!(
                " if ({k} != null) '{k}': {},",
                enc(f, &format!("{k}!.value"), true)
            ),
            (true, false) => format!(
                " if ({k} != null) '{k}': {},",
                encoded(&f["type"], &format!("{k}!"), true)
            ),
            (false, _) => format!(" '{k}': {},", enc(f, k, true)),
        };
        writeln!(o, "{line}").unwrap();
    }
    o.push_str(" };\n}\n");
}

// Model Fetch ([#153](https://github.com/zanminwang/axton/issues/153)): one
// method per Model that reads its complete snapshot through the existing
// Loader at the Model's local read version. The SDK's raw `fetchModel` submits
// the Rust task; these only encode the identity and decode each caller's own
// result with the Model's codecs. Nothing is emitted for a schema without
// Models, and nothing reaches the transaction facades.
fn has_models(v: &Value) -> bool {
    !arr(&v["schema"], "models").is_empty()
}
fn ts_fetch(v: &Value, o: &mut String) {
    if !has_models(v) {
        return;
    }
    let models = arr(&v["schema"], "models");
    o.push_str("export interface FetchPort { fetchModel<T>(model:string,version:number,identity:object,decode:(row:Record<string,unknown>)=>T,options?:{store?:boolean}):Promise<T|null>; }\n");
    o.push_str("/** One-shot remote reads: the complete snapshot through the Model's Loader, or null. `store: false` skips local cache writes. */\nexport interface FetchModels {\n");
    for m in models {
        let n = s(m, "name");
        writeln!(
            o,
            " {}(identity:{n}Identity, options?:{{store?:boolean}}):Promise<{n}|null>;",
            lower(n)
        )
        .unwrap();
    }
    o.push_str("}\nexport function fetchModels(port:FetchPort):FetchModels { return {\n");
    for m in models {
        let n = s(m, "name");
        writeln!(
            o,
            " {}:(identity,options)=>port.fetchModel('{n}',{},encode{n}Identity(identity),decode{n},options),",
            lower(n),
            m["version"]
        )
        .unwrap();
    }
    o.push_str("}; }\n");
}
fn dart_fetch(v: &Value, o: &mut String) {
    if !has_models(v) {
        return;
    }
    o.push_str("/// One-shot remote reads: the complete snapshot through the Model's Loader, or null. `store: false` skips local cache writes.\nclass FetchModels { final Client _client; FetchModels(this._client);\n");
    for m in arr(&v["schema"], "models") {
        let n = s(m, "name");
        writeln!(
            o,
            " Future<{n}?> {}({n}Identity identity, {{bool store = true}}) => _client.fetchModel('{n}', {}, identity.toRecord(), {n}.fromRecord, store: store);",
            lower(n),
            m["version"]
        )
        .unwrap();
    }
    o.push_str("}\n");
}
