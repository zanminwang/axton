/// Backend surface bound to the compiled schema. `runtime` is the import specifier of `@axtonjs/server`.
pub fn backend_typescript(v: &Value, runtime: &str) -> String {
    let mut o = String::from("// Generated by axton. Do not edit.\n");
    let has_actions = !arr(v, "actions").is_empty();
    writeln!(o, "import {{ createBackend as createRuntimeBackend, type BackendOptions, type LoaderCall }} from \"{runtime}\";").unwrap();
    if arr(v, "mutations").is_empty() {
        writeln!(
            o,
            "export {{ CallRejected, devAuth, type LoaderCall }} from \"{runtime}\";"
        )
        .unwrap();
    } else {
        writeln!(o, "export {{ CallRejected, MutationRejected, devAuth, type LoaderCall }} from \"{runtime}\";").unwrap();
    }
    let models = arr(&v["schema"], "models");
    let names: Vec<String> = models
        .iter()
        .flat_map(|m| {
            let n = s(m, "name");
            [
                format!("{n} as {n}Record"),
                format!("{n}Identity"),
                format!("{n}Patch"),
            ]
        })
        .collect();
    let mut names = names;
    if has_actions {
        for en in arr(&v["schema"], "enums") {
            names.push(s(en, "name").to_string());
        }
    }
    if has_actions {
        for m in models {
            let n = s(m, "name");
            names.extend([format!("{n}Update"), format!("{n}Delete")]);
        }
    }
    writeln!(
        o,
        "import type {{ {} }} from \"./generated.ts\";",
        names.join(", ")
    )
    .unwrap();
    for m in models {
        let n = s(m, "name");
        writeln!(o, "export type {n} = {n}Record;").unwrap();
        writeln!(o, "export type {{ {n}Identity, {n}Patch }};").unwrap();
        writeln!(o, "export function {n}(identity: {n}Identity): Extract<RecordRef, {{ model: \"{n}\" }}> {{ return {{ model: \"{n}\", identity }}; }}").unwrap();
    }
    ts_declarations(models, &mut o);
    let mut backend = v.clone();
    backend.as_object_mut().unwrap().remove("mutations");
    backend.as_object_mut().unwrap().remove("backendMutations");
    if let Some(history) = v.get("backendModels") {
        backend["models"] = history.clone();
        backend.as_object_mut().unwrap().remove("backendModels");
    }
    writeln!(o, "const schema = {} as const;", backend).unwrap();
    let actions = arr(v, "actions");
    let current = CurrentOperations::new(v);
    if has_actions {
        o.push_str("/** Trusted framework context and caller-supplied arguments of a Mutation. */\nexport type MutationHandlerCall<Tx, Args> = { ctx: MutationContext<Tx>; args: Args };\n/** A Query's context has no `stream` or `invalidate`: it reads without business side effects. */\nexport type QueryHandlerCall<Tx, Args> = { ctx: QueryContext<Tx>; args: Args };\n");
        for action in actions {
            let latest = current.version(s(action, "name"));
            if action["version"].as_u64() != Some(latest) {
                let prefix = action_type_name(action, latest, "");
                for model in arr(&action["input"], "models") {
                    let n = s(model, "name");
                    for (suffix, identity_only, patch_only) in [
                        ("Create", false, false),
                        ("Identity", true, false),
                        ("Patch", false, true),
                    ] {
                        writeln!(o, "export interface {prefix}{n}{suffix} {{").unwrap();
                        for field in arr(model, "fields") {
                            let is_id = arr(model, "identity").contains(&field["name"]);
                            if (identity_only && !is_id) || (patch_only && is_id) {
                                continue;
                            }
                            writeln!(
                                o,
                                " {}{}: {};",
                                s(field, "name"),
                                if patch_only { "?" } else { "" },
                                snapshot_field_type(field, &action["input"]["enums"])
                            )
                            .unwrap();
                        }
                        o.push_str("}\n");
                    }
                    writeln!(o, "export type {prefix}{n}Update<K extends keyof {prefix}{n}Patch = keyof {prefix}{n}Patch> = {prefix}{n}Identity & Partial<Pick<{prefix}{n}Patch, K>>;").unwrap();
                }
            }
            let input = action_type_name(action, latest, "Input");
            let output = action_type_name(action, latest, "HandlerOutput");
            writeln!(o, "export interface {input} {{").unwrap();
            for arg in arr(action, "inputs") {
                let optional = arg["kind"] == "model" && arg["cardinality"] == "optional";
                writeln!(
                    o,
                    " {}{}: {};",
                    s(arg, "name"),
                    if optional { "?" } else { "" },
                    historical_action_input_type(arg, action, latest)
                )
                .unwrap();
            }
            o.push_str("}\n");
            if arr(action, "outputs")
                .iter()
                .all(|field| field["source"].is_object())
            {
                writeln!(o, "export type {output} = void;").unwrap();
            } else {
                writeln!(o, "export interface {output} {{").unwrap();
                for field in arr(action, "outputs") {
                    if field["source"].is_object() {
                        continue;
                    }
                    writeln!(
                        o,
                        " {}: {};",
                        s(field, "name"),
                        backend_action_output_type(field, action, models)
                    )
                    .unwrap();
                }
                o.push_str("}\n");
            }
        }
    }
    // Operation registration follows each retained version's own kind, so a
    // name that changed kind at a new version registers each version under
    // its matching map. A bare function is shorthand only when the group
    // holds v1 alone.
    let mut groups = [false, false];
    for (index, (kind, interface, call)) in [
        (
            axton_core::CallKind::Mutation,
            "Mutations",
            "MutationHandlerCall",
        ),
        (axton_core::CallKind::Query, "Queries", "QueryHandlerCall"),
    ]
    .into_iter()
    .enumerate()
    {
        writeln!(o, "export interface {interface}<Tx> {{").unwrap();
        for (name, _, _) in current.iter() {
            let mut versions: Vec<&Value> = actions
                .iter()
                .filter(|a| s(a, "name") == name && crate::action_names::kind(a) == kind)
                .collect();
            if versions.is_empty() {
                continue;
            }
            groups[index] = true;
            versions.sort_by_key(|a| a["version"].as_u64().unwrap());
            let members = versions
                .iter()
                .map(|a| {
                    let input = action_type_name(a, current.version(name), "Input");
                    let output = action_type_name(a, current.version(name), "HandlerOutput");
                    format!(
                        "v{}(call: {call}<Tx, {input}>): Promise<{output}>;",
                        a["version"].as_u64().unwrap()
                    )
                })
                .collect::<Vec<_>>()
                .join(" ");
            let grouped = format!("{{ {} }}", members.trim_end_matches(';'));
            if versions.len() == 1 && versions[0]["version"].as_u64() == Some(1) {
                let input = action_type_name(versions[0], current.version(name), "Input");
                let output = action_type_name(versions[0], current.version(name), "HandlerOutput");
                writeln!(
                    o,
                    " {}: {grouped} | ((call: {call}<Tx, {input}>) => Promise<{output}>);",
                    lower(name)
                )
                .unwrap();
            } else {
                writeln!(o, " {}: {grouped};", lower(name)).unwrap();
            }
        }
        o.push_str("}\n");
    }

    // Every retained model read contract: the schema's own version is the
    // latest and keeps the plain record name; an older version is its own
    // record type with the enum values of its time inline, so a loader of that
    // version cannot be typed against a value the contract never promised.
    let retained: Vec<Value> = match backend.get("models").and_then(Value::as_array) {
        Some(list) => list.clone(),
        None => models
            .iter()
            .map(|m| {
                let mut snapshot = m.clone();
                snapshot["enums"] = arr(&v["schema"], "enums")
                    .iter()
                    .filter(|e| {
                        arr(m, "fields")
                            .iter()
                            .any(|f| f["type"]["kind"] == "enum" && f["type"]["name"] == e["name"])
                    })
                    .cloned()
                    .collect();
                snapshot
            })
            .collect(),
    };
    let record_name = |contract: &Value| {
        let n = s(contract, "name");
        let current = models
            .iter()
            .find(|m| m["name"] == contract["name"])
            .map(|m| m["version"].as_u64().unwrap_or(1));
        if Some(contract["version"].as_u64().unwrap()) == current {
            n.to_string()
        } else {
            format!("{n}V{}", contract["version"])
        }
    };
    for contract in &retained {
        let name = record_name(contract);
        if name == s(contract, "name") {
            continue;
        }
        writeln!(o, "export interface {name}Identity {{").unwrap();
        for f in arr(contract, "fields") {
            if arr(contract, "identity").contains(&f["name"]) {
                writeln!(
                    o,
                    " {}: {};",
                    s(f, "name"),
                    snapshot_field_type(f, &contract["enums"])
                )
                .unwrap();
            }
        }
        o.push_str("}\n");
        writeln!(o, "export interface {name} {{").unwrap();
        for f in arr(contract, "fields") {
            let field_type = if f["type"]["kind"] == "enum" {
                let en = arr(contract, "enums")
                    .iter()
                    .find(|e| e["name"] == f["type"]["name"])
                    .expect("a retained contract carries the enums its fields use");
                format!(
                    "{}{}",
                    arr(en, "values")
                        .iter()
                        .map(Value::to_string)
                        .collect::<Vec<_>>()
                        .join(" | "),
                    if f["nullable"] == true { " | null" } else { "" }
                )
            } else {
                ft(f, false)
            };
            writeln!(o, " {}: {field_type};", s(f, "name")).unwrap();
        }
        o.push_str("}\n");
    }
    // Loader registration mirrors handlers: every retained version under the
    // model name, a bare function only for a v1-only model. Each member is
    // optional: a Model without a Loader is device-only (#187), and the
    // backend refuses at startup a descriptor that would put it on the wire.
    // `| undefined` keeps `Loaders<Tx>["model"]` assignable back to its member
    // under `exactOptionalPropertyTypes`; the runtime reads it as omitted.
    o.push_str("export interface Loaders<Tx> {\n");
    for m in models {
        let n = s(m, "name");
        let mut versions: Vec<&Value> =
            retained.iter().filter(|c| c["name"] == m["name"]).collect();
        versions.sort_by_key(|c| c["version"].as_u64().unwrap());
        let members: Vec<String> = versions
            .iter()
            .map(|c| {
                format!(
                    "v{}(call: LoaderCall<Tx, {}Identity>): Promise<readonly ({} | null)[]>;",
                    c["version"].as_u64().unwrap(),
                    record_name(c),
                    record_name(c)
                )
            })
            .collect();
        let grouped = format!("{{ {} }}", members.join(" ").trim_end_matches(';'));
        if versions.len() == 1 && versions[0]["version"].as_u64() == Some(1) {
            writeln!(
                o,
                " {}?: {grouped} | ((call: LoaderCall<Tx, {n}Identity>) => Promise<readonly ({n} | null)[]>) | undefined;",
                lower(n)
            )
            .unwrap();
        } else {
            writeln!(o, " {}?: {grouped} | undefined;", lower(n)).unwrap();
        }
    }
    o.push_str("}\n");
    o.push_str("export interface PreparationContext<Tx> { tx:Tx; userId:string; streams(names:readonly string[]):Stream; invalidate:RecordDeclaration; }\nexport interface LoaderHooks<Tx> {\n");
    for model in models {
        let name = s(model, "name");
        writeln!(o," {}?: {{ prepareForViewer(call:LoaderCall<Tx,{name}Identity> & PreparationContext<Tx>):Promise<void> }};",lower(name)).unwrap();
    }
    o.push_str("}\n");
    let optional = |present: bool| if present { "" } else { "?" };
    writeln!(o, "export type Options<Tx> = Omit<BackendOptions<Tx>, \"config\" | \"mutations\" | \"queries\" | \"loaders\" | \"bootstrap\" | \"loaderHooks\" | \"protocol5\"> & {{ mutations{}: Mutations<Tx>; queries{}: Queries<Tx>; loaders: Loaders<Tx>; protocol5: NonNullable<BackendOptions<Tx>[\"protocol5\"]>; bootstrap?: (call: {{ctx: QueryContext<Tx>}}) => void | Promise<void>; loaderHooks?:LoaderHooks<Tx> }};", optional(groups[0]),optional(groups[1])).unwrap();
    o.push_str("export function createBackend<Tx>(options:Options<Tx>) { const {bootstrap,loaderHooks,...rest}=options;\n");
    o.push_str(" return createRuntimeBackend<Tx,TransactionCall<Tx>>({...rest,config:schema, mutations:options.mutations as unknown as BackendOptions<Tx>['mutations'],queries:options.queries as unknown as BackendOptions<Tx>['queries'],loaders:options.loaders as unknown as BackendOptions<Tx>['loaders'],...(bootstrap===undefined?{}:{bootstrap:bootstrap as unknown as NonNullable<BackendOptions<Tx>['bootstrap']>}),...(loaderHooks===undefined?{}:{loaderHooks:loaderHooks as unknown as NonNullable<BackendOptions<Tx>['loaderHooks']>})});\n}\n");
    o
}
/// The generated declaration API ([#140](https://github.com/zanminwang/axton/issues/140)):
/// a discriminated `RecordRef`, typed Stream tracking and invalidation
/// under each Model's lower-first accessor, and the concrete contexts
/// that carry them. A Query context carries neither.
fn ts_declarations(models: &[Value], o: &mut String) {
    let refs: Vec<String> = models
        .iter()
        .map(|m| {
            let n = s(m, "name");
            format!("{{ readonly model: \"{n}\"; readonly identity: {n}Identity }}")
        })
        .collect();
    writeln!(
        o,
        "export type RecordRef = {};",
        if refs.is_empty() {
            "never".to_string()
        } else {
            refs.join(" | ")
        }
    )
    .unwrap();
    crate::emit_stream::backend(models, o);
    o.push_str("export interface MutationContext<Tx> {\n tx: Tx;\n userId: string;\n callId: string;\n readonly stream: Stream;\n streams(names: readonly string[]): Stream;\n invalidate: RecordDeclaration;\n}\n");
    o.push_str(
        "export interface QueryContext<Tx> {\n tx: Tx;\n userId: string;\n callId: string;\n readonly stream: LoadStream;\n streams(names: readonly string[]): LoadStream;\n}\n",
    );
    o.push_str("export interface TransactionCall<Tx> {\n tx: Tx;\n streams(names: readonly string[]): Stream;\n invalidate: RecordDeclaration;\n}\n");
}
fn dart_action_type(ty_value: &Value) -> String {
    ty(ty_value, true)
}
fn dart_snapshot_type(ty_value: &Value, prefix: &str, enums: &Value) -> String {
    if ty_value["kind"] == "list" {
        return format!(
            "List<{}>",
            dart_snapshot_type(&ty_value["element"], prefix, enums)
        );
    }
    if ty_value["kind"] == "enum"
        && enums
            .as_array()
            .is_some_and(|items| items.iter().any(|e| e["name"] == ty_value["name"]))
    {
        return format!("{prefix}{}", s(ty_value, "name"));
    }
    dart_action_type(ty_value)
}
fn dart_snapshot_field(field: &Value, prefix: &str, enums: &Value) -> String {
    let base = dart_snapshot_type(&field["type"], prefix, enums);
    if field["nullable"] == true {
        format!("{base}?")
    } else {
        base
    }
}
fn dart_action_cardinality(base: &str, cardinality: &str) -> String {
    match cardinality {
        "optional" => format!("{base}?"),
        "list" => format!("List<{base}>"),
        _ => base.to_string(),
    }
}
/// An operation input's Dart type. A current create operand is a
/// `{Model}CreateInput` for the `client`, which may omit defaulted fields;
/// handlers receive the complete record.
pub(crate) fn dart_action_input_type(
    arg: &Value,
    prefix: &str,
    restriction_prefix: &str,
    enums: &Value,
    restricted: bool,
    client: bool,
) -> String {
    if arg["kind"] == "value" {
        let base = dart_snapshot_type(&arg["type"], prefix, enums);
        return if arg["list"] == true {
            format!("List<{base}>")
        } else if arg["nullable"] == true {
            format!("{base}?")
        } else {
            base
        };
    }
    let model = s(arg, "model");
    let base = match s(arg, "operation") {
        "create" if !prefix.is_empty() => format!("{prefix}{model}Create"),
        "create" if client => format!("{model}CreateInput"),
        "create" => model.to_string(),
        "delete" => format!("{prefix}{model}Delete"),
        "update" if restricted => format!(
            "{restriction_prefix}{}{}Update",
            upper(s(arg, "name")),
            if prefix.is_empty() { "" } else { "Slot" }
        ),
        "update" => format!("{prefix}{model}Update"),
        _ => unreachable!(),
    };
    dart_action_cardinality(&base, s(arg, "cardinality"))
}
fn dart_action_output_type(
    field: &Value,
    identity: bool,
    output_prefix: &str,
    output_enums: &Value,
    models: &[Value],
) -> String {
    let base = match s(field, "kind") {
        "value" => dart_snapshot_type(&field["type"], output_prefix, output_enums),
        "deleteIdentity" => format!("{}Identity", s(field, "model")),
        "model" if identity => {
            let model = s(field, "model");
            let current = models
                .iter()
                .find(|m| m["name"] == model)
                .and_then(|m| m["version"].as_u64());
            let read = field["modelReadVersion"].as_u64();
            match read {
                Some(version) if Some(version) != current => {
                    format!("{model}V{version}Identity")
                }
                _ => format!("{model}Identity"),
            }
        }
        "model" => s(field, "model").to_string(),
        _ => unreachable!(),
    };
    dart_action_cardinality(&base, s(field, "cardinality"))
}

fn dart_data_class(o: &mut String, name: &str, fields: &[(String, String, bool)]) {
    writeln!(o, "class {name} implements _DartActionRecord {{").unwrap();
    for (field, ty, _) in fields {
        writeln!(o, " final {ty} {field};").unwrap();
    }
    let params = fields
        .iter()
        .map(|(field, _, required)| {
            format!("{}this.{field}", if *required { "required " } else { "" })
        })
        .collect::<Vec<_>>()
        .join(",");
    writeln!(
        o,
        " const {name}({});",
        if fields.is_empty() {
            String::new()
        } else {
            format!("{{{params}}}")
        }
    )
    .unwrap();
    o.push_str(" Map<String,dynamic> toRecord() => {\n");
    for (field, ty, _) in fields {
        if ty.starts_with("Present<") {
            writeln!(
                o,
                " if ({field} != null) '{field}': _dartActionEncode({field}!.value),"
            )
            .unwrap();
        } else {
            writeln!(o, " '{field}': _dartActionEncode({field}),").unwrap();
        }
    }
    o.push_str(" };\n}\n");
}
fn dart_action_update(
    o: &mut String,
    name: &str,
    model: &Value,
    allowed: Option<&Vec<Value>>,
    prefix: &str,
    enums: &Value,
) {
    let mut fields = vec![];
    for field in arr(model, "fields") {
        let key = s(field, "name");
        if arr(model, "identity").contains(&field["name"]) {
            fields.push((
                key.to_string(),
                dart_snapshot_field(field, prefix, enums),
                true,
            ));
        } else if allowed.is_none_or(|a| a.contains(&field["name"])) {
            fields.push((
                key.to_string(),
                format!("Present<{}>?", dart_snapshot_field(field, prefix, enums)),
                false,
            ));
        }
    }
    dart_data_class(o, name, &fields);
}
fn dart_actions(v: &Value, current: &CurrentOperations<'_>, o: &mut String) {
    let actions = arr(v, "actions");
    if actions.is_empty() {
        return;
    }
    o.push_str("/// Public Action lifecycle types are owned by the SDK.\n");
    let models = arr(&v["schema"], "models");
    for model in models {
        let n = s(model, "name");
        writeln!(o, "typedef {n}Delete = {n}Identity;").unwrap();
        dart_action_update(o, &format!("{n}Update"), model, None, "", &Value::Null);
    }
    let mut emitted_reads = std::collections::BTreeSet::new();
    for model in v
        .get("backendModels")
        .and_then(Value::as_array)
        .into_iter()
        .flatten()
    {
        let name = s(model, "name");
        let version = model["version"].as_u64().unwrap_or(1);
        let current = models
            .iter()
            .find(|m| m["name"] == name)
            .and_then(|m| m["version"].as_u64());
        if Some(version) == current || !emitted_reads.insert((name.to_string(), version)) {
            continue;
        }
        let fields = arr(model, "fields")
            .iter()
            .filter(|field| arr(model, "identity").contains(&field["name"]))
            .map(|field| (s(field, "name").to_string(), ft(field, true), true))
            .collect::<Vec<_>>();
        dart_data_class(o, &format!("{name}V{version}Identity"), &fields);
    }
    for action in actions {
        let name = s(action, "name");
        let is_latest = action["version"].as_u64() == Some(current.version(name));
        let prefix = action_type_name(action, current.version(name), "");
        let historical = if is_latest { "" } else { prefix.as_str() };
        let input_enums = if is_latest {
            &Value::Null
        } else {
            &action["input"]["enums"]
        };
        if !is_latest {
            let mut seen = std::collections::BTreeSet::new();
            for en in input_enums.as_array().into_iter().flatten() {
                let name = s(en, "name");
                if seen.insert(name) {
                    writeln!(
                        o,
                        "enum {prefix}{name} {{ {} }}",
                        arr(en, "values")
                            .iter()
                            .map(Value::as_str)
                            .map(Option::unwrap)
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                    .unwrap();
                }
            }
            for model in arr(&action["input"], "models") {
                let model_name = s(model, "name");
                for (suffix, identity_only) in
                    [("Create", false), ("Identity", true), ("Delete", true)]
                {
                    let fields = arr(model, "fields")
                        .iter()
                        .filter(|field| {
                            !identity_only || arr(model, "identity").contains(&field["name"])
                        })
                        .map(|field| {
                            (
                                s(field, "name").to_string(),
                                dart_snapshot_field(field, &prefix, input_enums),
                                true,
                            )
                        })
                        .collect::<Vec<_>>();
                    dart_data_class(o, &format!("{prefix}{model_name}{suffix}"), &fields);
                }
                dart_action_update(
                    o,
                    &format!("{prefix}{model_name}Update"),
                    model,
                    None,
                    &prefix,
                    input_enums,
                );
            }
        }
        for arg in arr(action, "inputs") {
            if arg["kind"] == "model"
                && arg["operation"] == "update"
                && arg["allowedPatchFields"].is_array()
            {
                let model = action["input"]["models"]
                    .as_array()
                    .into_iter()
                    .flatten()
                    .chain(models.iter())
                    .find(|m| m["name"] == arg["model"])
                    .unwrap();
                dart_action_update(
                    o,
                    &format!(
                        "{prefix}{}{}Update",
                        upper(s(arg, "name")),
                        if is_latest { "" } else { "Slot" }
                    ),
                    model,
                    arg["allowedPatchFields"].as_array(),
                    historical,
                    input_enums,
                );
            }
        }
        let inputs = arr(action, "inputs")
            .iter()
            .map(|arg| {
                let optional = arg["kind"] == "model" && arg["cardinality"] == "optional";
                (
                    s(arg, "name").to_string(),
                    dart_action_input_type(
                        arg,
                        historical,
                        &prefix,
                        input_enums,
                        arg["allowedPatchFields"].is_array(),
                        false,
                    ),
                    !optional,
                )
            })
            .collect::<Vec<_>>();
        if is_latest {
            dart_data_class(o, &format!("{prefix}HandlerInput"), &inputs);
            let client_inputs = arr(action, "inputs")
                .iter()
                .map(|arg| {
                    let optional = arg["kind"] == "model" && arg["cardinality"] == "optional";
                    (
                        s(arg, "name").to_string(),
                        dart_action_input_type(
                            arg,
                            historical,
                            &prefix,
                            input_enums,
                            arg["allowedPatchFields"].is_array(),
                            true,
                        ),
                        !optional,
                    )
                })
                .collect::<Vec<_>>();
            dart_data_class(o, &format!("{prefix}Input"), &client_inputs);
        } else {
            dart_data_class(o, &format!("{prefix}Input"), &inputs);
        }

        let outputs = arr(action, "outputs");
        let output_prefix = if is_latest {
            String::new()
        } else {
            format!("{prefix}Output")
        };
        let output_enums = if is_latest {
            &Value::Null
        } else {
            &action["outputEnums"]
        };
        if !is_latest {
            let mut seen = std::collections::BTreeSet::new();
            for en in output_enums.as_array().into_iter().flatten() {
                let name = s(en, "name");
                if seen.insert(name) {
                    writeln!(
                        o,
                        "enum {output_prefix}{name} {{ {} }}",
                        arr(en, "values")
                            .iter()
                            .map(Value::as_str)
                            .map(Option::unwrap)
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                    .unwrap();
                }
            }
        }
        if is_latest {
            if outputs.is_empty() {
                writeln!(o, "typedef {prefix}Output = void;").unwrap();
            } else {
                let fields = outputs
                    .iter()
                    .map(|field| {
                        (
                            s(field, "name").to_string(),
                            dart_action_output_type(field, false, "", &Value::Null, models),
                            true,
                        )
                    })
                    .collect::<Vec<_>>();
                dart_data_class(o, &format!("{prefix}Output"), &fields);
            }
        }
        let explicit = outputs
            .iter()
            .filter(|field| !field["source"].is_object())
            .collect::<Vec<_>>();
        if explicit.is_empty() {
            writeln!(o, "typedef {prefix}HandlerOutput = void;").unwrap();
        } else {
            let fields = explicit
                .iter()
                .map(|field| {
                    (
                        s(field, "name").to_string(),
                        dart_action_output_type(field, true, &output_prefix, output_enums, models),
                        true,
                    )
                })
                .collect::<Vec<_>>();
            dart_data_class(o, &format!("{prefix}HandlerOutput"), &fields);
        }
    }

    // Handler contracts group each retained version under its own kind.
    for (kind, label) in [
        (axton_core::CallKind::Mutation, "Mutation"),
        (axton_core::CallKind::Query, "Query"),
    ] {
        let of_kind = |name: &str| -> Vec<&Value> {
            actions
                .iter()
                .filter(|a| s(a, "name") == name && crate::action_names::kind(a) == kind)
                .collect()
        };
        writeln!(o, "abstract interface class {label}HandlerCall<Ctx, Args> {{ Ctx get ctx; Args get args; }}\nabstract interface class {label}Handlers<Ctx> {{").unwrap();
        for (name, _, _) in current.iter() {
            if !of_kind(name).is_empty() {
                writeln!(o, " {label}{}Handlers<Ctx> get {};", name, lower(name)).unwrap();
            }
        }
        o.push_str("}\n");
        for (name, version, _) in current.iter() {
            if of_kind(name).is_empty() {
                continue;
            }
            writeln!(o, "abstract interface class {label}{name}Handlers<Ctx> {{").unwrap();
            for action in of_kind(name) {
                let prefix = action_type_name(action, version, "");
                writeln!(
                    o,
                    " Future<{prefix}HandlerOutput> v{}({label}HandlerCall<Ctx, {prefix}{}> call);",
                    action["version"],
                    if action["version"].as_u64() == Some(version) {
                        "HandlerInput"
                    } else {
                        "Input"
                    }
                )
                .unwrap();
            }
            o.push_str("}\n");
        }
    }
}
fn dart_action_decode_field(field: &Value, value: &str) -> String {
    let one = |x: &str| -> String {
        match s(field, "kind") {
            "value" => decode(&field["type"], x, true),
            "model" => format!(
                "{}.fromRecord(({x} as Map).cast<String,dynamic>())",
                s(field, "model")
            ),
            "deleteIdentity" => format!(
                "{}Identity.fromRecord(({x} as Map).cast<String,dynamic>())",
                s(field, "model")
            ),
            _ => unreachable!(),
        }
    };
    let cardinality = s(field, "cardinality");
    if cardinality == "list" {
        return format!("({value} as List).map((e) => {}).toList()", one("e"));
    }
    if cardinality == "optional" || (field["kind"] == "value" && field["nullable"] == true) {
        return format!("{value} == null ? null : {}", one(value));
    }
    one(value)
}
fn dart_action_runtime(v: &Value, current: &CurrentOperations<'_>, o: &mut String) {
    let actions = arr(v, "actions");
    if actions.is_empty() {
        return;
    }
    o.push_str("dynamic _dartActionEncode(dynamic value) {\n if (value == null) return null;\n if (value is DateTime) return value.toAxtonPrecision().toIso8601String();\n if (value is Enum) return value.name;\n if (value is List) return value.map(_dartActionEncode).toList();\n if (value is _DartActionRecord) return value.toRecord();\n");
    for model in arr(&v["schema"], "models") {
        let n = s(model, "name");
        writeln!(o, " if (value is {n}) return value.toRecord();\n if (value is {n}CreateInput) return value.toCreateRecord();\n if (value is {n}Identity) return value.toRecord();").unwrap();
    }
    o.push_str(" return value;\n}\n");
    if !current.has_mutations() {
        o.push_str("class Mutations { Mutations(Client client); }\n");
    } else {
        o.push_str("/// Named Mutations use the same owned local scope on client and transaction.\nclass Mutations extends TransactionMutations { Mutations(super.port); }\n");
    }
    o.push_str("/// Query results are invocation snapshots.\nclass Queries {\n final Client client; Queries(this.client);\n");
    for (name, version, action) in current.iter() {
        if crate::action_names::kind(action) != axton_core::CallKind::Query {
            continue;
        }
        let params = dart_action_params(action);
        let store = dart_store_param(action);
        let controls = format!("bool {store} = true");
        let signature = if params.is_empty() {
            controls
        } else {
            format!("{params}, {controls}")
        };
        writeln!(o, " Future<{name}Output> {}({{{signature}}}) => this.client.invokeQuery<{name}Output>('{name}', {version}, {{{}}}, {}, store: {store});", lower(name), dart_action_arguments(action), dart_action_decoder(action, name)).unwrap();
    }
    o.push_str("}\n");
}
/// The Dart closure decoding an operation's `{name}Output` from its wire value.
pub(crate) fn dart_action_decoder(action: &Value, name: &str) -> String {
    let outputs = arr(action, "outputs");
    if outputs.is_empty() {
        return "(_) {}".to_string();
    }
    let fields = outputs
        .iter()
        .map(|field| {
            let key = s(field, "name");
            let value = format!("row['{key}']");
            format!("{key}: {}", dart_action_decode_field(field, &value))
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!(
        "(value) {{ final row = (value as Map).cast<String,dynamic>(); return {name}Output({fields}); }}"
    )
}
/// The business args map of a Dart operation call.
pub(crate) fn dart_action_arguments(action: &Value) -> String {
    arr(action, "inputs")
        .iter()
        .map(|arg| {
            let key = s(arg, "name");
            if arg["kind"] == "model" && arg["cardinality"] == "optional" {
                format!("if ({key} != null) '{key}': _dartActionEncode({key})")
            } else {
                format!("'{key}': _dartActionEncode({key})")
            }
        })
        .collect::<Vec<_>>()
        .join(", ")
}
pub(crate) fn dart_action_params(action: &Value) -> String {
    arr(action, "inputs")
        .iter()
        .map(|arg| {
            let optional = arg["kind"] == "model" && arg["cardinality"] == "optional";
            format!(
                "{}{} {}",
                if optional { "" } else { "required " },
                dart_action_input_type(
                    arg,
                    "",
                    s(action, "name"),
                    &Value::Null,
                    arg["allowedPatchFields"].is_array(),
                    true,
                ),
                s(arg, "name")
            )
        })
        .collect::<Vec<_>>()
        .join(", ")
}

